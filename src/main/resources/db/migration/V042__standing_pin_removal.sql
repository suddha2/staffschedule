-- V042: removing standing pins from the Standing Pins screen (2026-11-02). Each removal and the
-- pins it took out are kept here, so it can be reviewed and undone.
BEGIN;

CREATE TABLE IF NOT EXISTS standing_pin_removal (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    region      varchar(30) NOT NULL,
    removed_by  varchar(100),
    removed_at  timestamp NOT NULL DEFAULT now(),
    pin_count   integer NOT NULL DEFAULT 0,
    carers      text,
    undone_by   varchar(100),
    undone_at   timestamp
);

CREATE INDEX IF NOT EXISTS idx_standing_pin_removal_region ON standing_pin_removal (region, id DESC);

CREATE TABLE IF NOT EXISTS standing_pin_removal_item (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    removal_id        bigint NOT NULL REFERENCES standing_pin_removal (id) ON DELETE CASCADE,
    shift_template_id bigint NOT NULL,
    employee_id       bigint NOT NULL,
    week_of_period    smallint NOT NULL,
    pinned_at         timestamp,
    pinned_by_user_id bigint
);

CREATE INDEX IF NOT EXISTS idx_standing_pin_removal_item ON standing_pin_removal_item (removal_id);

COMMIT;
