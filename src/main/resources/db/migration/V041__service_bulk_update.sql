-- V041: bulk rename, merge or remove of a service name (2026-11-02). A service name is stored as
-- text in several tables, so one update touches many rows. Each run and the old value of every
-- row it changed are kept here, so the run can be reviewed and undone.
BEGIN;

CREATE TABLE IF NOT EXISTS service_bulk_update (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    region      varchar(30) NOT NULL,
    action      varchar(10) NOT NULL,
    name        text NOT NULL,
    new_name    text,
    changed_by  varchar(100),
    changed_at  timestamp NOT NULL DEFAULT now(),
    row_count   integer NOT NULL DEFAULT 0,
    undone_by   varchar(100),
    undone_at   timestamp
);

CREATE INDEX IF NOT EXISTS idx_service_bulk_update_region ON service_bulk_update (region, id DESC);

CREATE TABLE IF NOT EXISTS service_bulk_update_change (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    update_id   bigint NOT NULL REFERENCES service_bulk_update (id) ON DELETE CASCADE,
    table_name  varchar(40) NOT NULL,
    row_id      varchar(40) NOT NULL,
    column_name varchar(40) NOT NULL,
    old_value   text,
    new_value   text
);

CREATE INDEX IF NOT EXISTS idx_service_bulk_update_change ON service_bulk_update_change (update_id);

COMMIT;
